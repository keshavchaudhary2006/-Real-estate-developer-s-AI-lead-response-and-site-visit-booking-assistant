/**
 * Appends official RERA registration disclaimer to promotional messages.
 * Mandated for every promotional response.
 */
function appendReraNotice(content, projectId, reraNumber, lang = 'en') {
  const dict = DICTIONARY[lang] || DICTIONARY.en;
  const separator = '\n\n──────────────────────────────\n';
  const reraBadge = `🏛️ ${dict.reraPrefix}: ${reraNumber}\n📌 Project: ${projectId} | ${dict.jurisdictionNotice}`;
  return content + separator + reraBadge;
}

/**
 * Detect language of incoming user text
 */
function detectLanguage(text, currentLang = 'en') {
  if (!text) return currentLang;
  // Gujarati script unicode range: 0A80 - 0AFF
  if (/[\u0A80-\u0AFF]/.test(text)) return 'gu';
  // Devanagari (Hindi) script unicode range: 0900 - 097F
  if (/[\u0900-\u097F]/.test(text)) return 'hi';
  return currentLang;
}

